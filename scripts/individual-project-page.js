function createImage(item) {
  const img = document.createElement("img");

  img.src = item.src;

  img.loading = "lazy";

  img.alt = item.alt || "";

  img.className = "img";

  if (item.size) {
    img.setAttribute("size", item.size);
  }

  img.sizes =
    "(max-width: 375px) 500px, " +
    "(max-width: 768px) 600px, " +
    "(max-width: 1200px) 1000px, " +
    "(max-width: 1500px) 1500px, 2500px";

  return img;
}

